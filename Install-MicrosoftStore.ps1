Write-Log (T '\u0424\u0430\u0439\u043B\u043E\u0432 Store \u0432 \u0441\u0438\u0441\u0442\u0435\u043C\u0435 \u043D\u0435\u0442.') 'WARN'

# --- 2. wsreset -i ---
# Tried on every Windows build. On some builds wsreset runs for several minutes; on others it exits
# quickly and Store is installed in the background and appears later. So we wait for STORE to appear
# (up to -WsresetTimeout seconds counted from the start), not only for the wsreset process, and never
# start a second copy while the first is still running. If wsreset.exe is missing, fails, or Store does
# not appear in time, the script just moves on.
# Resolve wsreset the same way the shell does for a manual "wsreset -i" (PATH lookup).
# Fallback: the System32 path, or Sysnative when this is a 32-bit process on 64-bit Windows.
$wsCmd = Get-Command -Name 'wsreset' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
$wsreset = if ($wsCmd) { $wsCmd.Source } else {
    $wsDir = if (-not [Environment]::Is64BitProcess -and [Environment]::Is64BitOperatingSystem) { 'Sysnative' } else { 'System32' }
    Join-Path $env:SystemRoot "$wsDir\wsreset.exe"
}
if ($SkipWsreset) {
    Write-Log (T "\u0421\u043F\u043E\u0441\u043E\u0431 2 (wsreset -i) \u043F\u0440\u043E\u043F\u0443\u0449\u0435\u043D \u043F\u0430\u0440\u0430\u043C\u0435\u0442\u0440\u043E\u043C -SkipWsreset.")
} elseif (-not (Test-Path $wsreset)) {
    Write-Log (T "\u0421\u043F\u043E\u0441\u043E\u0431 2: wsreset.exe \u043D\u0435 \u043D\u0430\u0439\u0434\u0435\u043D, \u043F\u0435\u0440\u0435\u0445\u043E\u0434\u0438\u043C \u043A \u0441\u043B\u0435\u0434\u0443\u044E\u0449\u0435\u043C\u0443 \u0441\u043F\u043E\u0441\u043E\u0431\u0443.") 'WARN'
} else {
    Write-Log (T "\u0421\u043F\u043E\u0441\u043E\u0431 2: wsreset.exe -i (\u043E\u0436\u0438\u0434\u0430\u043D\u0438\u0435 \u043F\u043E\u044F\u0432\u043B\u0435\u043D\u0438\u044F Store \u0434\u043E $WsresetTimeout \u0441; \u043D\u0430 \u043D\u0435\u043A\u043E\u0442\u043E\u0440\u044B\u0445 \u0441\u0431\u043E\u0440\u043A\u0430\u0445 \u0443\u0441\u0442\u0430\u043D\u043E\u0432\u043A\u0430 \u0438\u0434\u0451\u0442 \u043D\u0435\u0441\u043A\u043E\u043B\u044C\u043A\u043E \u043C\u0438\u043D\u0443\u0442)")
    $svcInfo = foreach ($sn in 'InstallService', 'wuauserv', 'ClipSVC', 'AppXSvc') {
        $sv = Get-Service -Name $sn -ErrorAction SilentlyContinue
        if ($sv) { '{0}={1}/{2}' -f $sn, $sv.Status, $sv.StartType }
    }
    Write-Log ("Diagnostics: user $env:USERDOMAIN\$env:USERNAME; 64-bit process: $([Environment]::Is64BitProcess); wsreset: $wsreset; services: " + ($svcInfo -join ', '))
    $done = $false
    for ($attempt = 1; $attempt -le 2 -and -not $done; $attempt++) {
        $retry = $false
        try {
            Write-Log (T "\u041F\u043E\u043F\u044B\u0442\u043A\u0430 ${attempt}/2: \u0437\u0430\u043F\u0443\u0441\u043A wsreset.exe -i...")
            if ($attempt -eq 1) {
                $proc = Start-Process -FilePath $wsreset -ArgumentList '-i' -NoNewWindow -PassThru
            } else {
                # second try: typed the way it is done by hand, "wsreset -i" in a command shell
                $proc = Start-Process -FilePath $env:ComSpec -ArgumentList '/c wsreset -i' -NoNewWindow -PassThru
            }
            [void]$proc.Handle   # cache the handle so ExitCode is available after exit
            $sw = [Diagnostics.Stopwatch]::StartNew()
            $next = 30
            $exitLogged = $false
            $limit = $WsresetTimeout
            while ($sw.Elapsed.TotalSeconds -lt $limit) {
                if (Test-StoreInstalled) { $done = $true; break }
                if ($proc.HasExited -and -not $exitLogged) {
                    $exitLogged = $true
                    $code = if ($null -ne $proc.ExitCode) { $proc.ExitCode } else { 'n/a' }
                    # wsreset failed (non-zero exit code): do not wait the whole time, give it a short grace period
                    if ($code -is [int] -and $code -ne 0) { $limit = [Math]::Min($WsresetTimeout, [int]$sw.Elapsed.TotalSeconds + 60) }
                    Write-Log (T "wsreset \u0437\u0430\u0432\u0435\u0440\u0448\u0438\u043B\u0441\u044F \u0437\u0430 $([int]$sw.Elapsed.TotalSeconds) \u0441, \u043A\u043E\u0434 $code. Store \u0435\u0449\u0451 \u043D\u0435 \u043F\u043E\u044F\u0432\u0438\u043B\u0441\u044F: \u0436\u0434\u0451\u043C \u0435\u0433\u043E \u0434\u043E $limit \u0441 (\u0443\u0441\u0442\u0430\u043D\u043E\u0432\u043A\u0430 \u043C\u043E\u0436\u0435\u0442 \u0438\u0434\u0442\u0438 \u0432 \u0444\u043E\u043D\u0435).")
                }
                if ($sw.Elapsed.TotalSeconds -ge $next) {
                    $procState = if ($proc.HasExited) { 'exited' } else { 'running' }
                    Write-Log (T "\u041E\u0436\u0438\u0434\u0430\u043D\u0438\u0435... $([int]$sw.Elapsed.TotalSeconds) \u0441 (wsreset: $procState; Store: $(Get-StoreState))")
                    $next += 30
                }
                Start-Sleep -Seconds 3
            }
            if ($done) {
                if (-not $proc.HasExited) { [void]$proc.WaitForExit(60000) }   # Store is there: let wsreset finish
            } else {
                if (-not $proc.HasExited) {
                    Write-Log (T "wsreset \u043D\u0435 \u0437\u0430\u0432\u0435\u0440\u0448\u0438\u043B\u0441\u044F \u0437\u0430 $WsresetTimeout \u0441: \u043E\u0441\u0442\u0430\u043D\u0430\u0432\u043B\u0438\u0432\u0430\u0435\u043C \u0435\u0433\u043E \u0438 \u043F\u0435\u0440\u0435\u0445\u043E\u0434\u0438\u043C \u043A \u0441\u043B\u0435\u0434\u0443\u044E\u0449\u0435\u043C\u0443 \u0441\u043F\u043E\u0441\u043E\u0431\u0443.") 'WARN'
                    Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue
                } else {
                    $code = if ($null -ne $proc.ExitCode) { $proc.ExitCode } else { 'n/a' }
                    Write-Log (T "wsreset \u0437\u0430\u0432\u0435\u0440\u0448\u0438\u043B\u0441\u044F (\u043A\u043E\u0434 $code), \u043D\u043E Store \u043D\u0435 \u043F\u043E\u044F\u0432\u0438\u043B\u0441\u044F \u0437\u0430 $WsresetTimeout \u0441.") 'WARN'
                    # a failed run (non-zero exit code) is worth one more try; a clean exit is not repeated
                    if ($attempt -eq 1 -and $code -is [int] -and $code -ne 0) { $retry = $true }
                }
            }
        } catch {
            Write-Log "wsreset: $($_.Exception.Message)" 'WARN'
        }
        if (-not $done -and -not $retry) { break }
    }
    if ($done) { Finish }
    Write-Log (T "wsreset -i \u043D\u0435 \u0443\u0441\u0442\u0430\u043D\u043E\u0432\u0438\u043B Store, \u043F\u0435\u0440\u0435\u0445\u043E\u0434\u0438\u043C \u043A \u0441\u043B\u0435\u0434\u0443\u044E\u0449\u0435\u043C\u0443 \u0441\u043F\u043E\u0441\u043E\u0431\u0443.") 'WARN'
}

