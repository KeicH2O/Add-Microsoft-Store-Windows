function Test-StoreInstalled {
    $p = Get-AppxPackage -Name 'Microsoft.WindowsStore' -ErrorAction SilentlyContinue | Select-Object -First 1
    # registered for the current user and not in a broken state
    return ($null -ne $p -and (-not $p.Status -or $p.Status.ToString() -eq 'Ok'))
}

# Short description of the Store package state for the log
function Get-StoreState {
    $p = Get-AppxPackage -Name 'Microsoft.WindowsStore' -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $p) { return 'not found' }
    return ('{0} {1}' -f $p.Version, $p.Status)
}

function Wait-Store([int]$TimeoutSec) {
    $sw = [Diagnostics.Stopwatch]::StartNew()
    while ($sw.Elapsed.TotalSeconds -lt $TimeoutSec) {
        if (Test-StoreInstalled) { return $true }
        Start-Sleep -Seconds 5
    }
    return $false
}

