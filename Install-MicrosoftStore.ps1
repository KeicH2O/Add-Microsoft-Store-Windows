<#
.SYNOPSIS
    Installs (restores) Microsoft Store on Windows 10 / 11: LTSC, as well as Home / Pro / Education / Enterprise.

.DESCRIPTION
    Methods, in order (stops as soon as Store is present):
      1. Re-register existing Store files (AppXManifest.xml).
      2. wsreset.exe -i (tried on every build; Store may appear several minutes later, even after wsreset
         has exited; if wsreset is missing, fails or Store does not appear, the script moves on).
      3. Local folder with packages (-PackagePath).
      4. Cache of previously downloaded packages
         (%ProgramData%\MicrosoftStore-LTSC-Installer\packages).
      5. Download from the network. Sources (-Source):
           StoreCdn - Microsoft CDN links generated by store.rg-adguard.net;
           Mirror   - JSON manifest with package sets per Windows version (-ManifestUrl);
           Auto     - StoreCdn, then Mirror (on Windows 10 builds below 19041 the order is reversed).

    Every package is checked before installation: the signature must belong to Microsoft.
    The final signature validation is done by the Windows deployment engine.
    By default Store is also added to the system image (for new user accounts).

    Mirror manifest format (HTTPS only). The key is a set for a Windows version:
    Win11_24H2 (build 26100+), LTSC2021 (19044+), LTSC2019 (14393+):
      { "LTSC2021": { "deps": ["https://.../Microsoft.VCLibs.x64....appx", ...],
                      "store": "https://....msixbundle", "store_license": "https://....xml",
                      "StorePurchaseApp": "https://....msixbundle",
                      "StorePurchaseApp_license": "https://....xml" }, ... }
    Mirror sets are matched to a specific Windows version, while the CDN returns the newest
    Store, which may not install on older builds (LTSC 2019 / LTSB 2016).

.PARAMETER PackagePath      Folder with .appx/.msix/.appxbundle/.msixbundle files.
.PARAMETER Source           Download source: Auto, StoreCdn, Mirror.
.PARAMETER ManifestUrl      HTTPS address of the JSON manifest for the Mirror source.
.PARAMETER NoDownload       Do not download anything from the network.
.PARAMETER ForceDownload    Ignore the cache and download packages again.
.PARAMETER SkipWsreset      Skip wsreset -i.
.PARAMETER WsresetTimeout   Maximum seconds to wait for Store to appear after starting wsreset (30-3600, default 600).
.PARAMETER CurrentUserOnly  Do not add Store to the system image, install for the current user only.

.NOTES
    Easiest start: right-click the file -> "Run with PowerShell" (or double-click the optional
    Install-MicrosoftStore.cmd launcher). The script asks for administrator rights by itself.
    Log: %ProgramData%\MicrosoftStore-LTSC-Installer\install.log

    This file is pure ASCII on purpose: Russian messages are stored as \uXXXX escapes and
    decoded by the T function, so the script works whatever encoding the file is saved in
    (UTF-8 with or without BOM, ANSI).
#>
[CmdletBinding()]
